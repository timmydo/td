/// The box a scalar the face lacks draws.
const BOX: [u8; HEIGHT] = [0b1111, 0b1001, 0b1001, 0b1001, 0b1111];

/// The width of `text` in pixels: a glyph and a column of space each,
/// the last space left off; zero for nothing.
pub fn width(text: &str) -> usize {
    text.chars()
        .count()
        .saturating_mul(ADVANCE)
        .saturating_sub(ADVANCE - WIDTH)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_scalar_has_a_glyph_within_the_face_and_a_box_is_the_rest() {
        for scalar in (0x21u8..0x7f).map(char::from) {
            let rows = glyph(scalar);
            assert_ne!(rows, BOX, "{scalar}");
            assert!(rows.iter().any(|row| *row != 0), "{scalar}");
            assert!(rows.iter().all(|row| *row < 16), "{scalar}");
        }
        assert_eq!(glyph(' '), [0; HEIGHT]);
        assert_eq!(glyph('\u{e9}'), BOX);
        assert_eq!(width(""), 0);
        assert_eq!(width("F1"), 9);
        assert_eq!(width("Backspace"), 44);
    }

    #[test]
    fn the_cases_differ() {
        for scalar in 'a'..='z' {
            assert_ne!(
                glyph(scalar),
                glyph(scalar.to_ascii_uppercase()),
                "{scalar}"
            );
        }
    }
}
