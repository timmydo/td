//! The hint face: a 4 by 5 pixel glyph per printable ASCII scalar, for
//! the short lighter text a button shows under its caption while a
//! modifier is held (`chrome::Button::emit_hinted`). Hand-authored, no
//! source but this file; a scalar it lacks is drawn as a box.

/// A glyph's columns and rows, and the advance from one to the next
/// (a column of space between).
pub const WIDTH: usize = 4;
pub const HEIGHT: usize = 5;
pub const ADVANCE: usize = 5;

