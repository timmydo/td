/// d = -121665/121666, the Edwards parameter. Non-square in GF(p), which is
/// what makes the addition law below COMPLETE — no exceptional-case handling
/// for the identity, for doubling, or for adding a point to its own negative.
const D: Fe = Fe([
    0x34dca135978a3,
    0x1a8283b156ebd,
    0x5e7a26001c029,
    0x739c663a03cbb,
    0x52036cee2b6ff,
]);

/// 2d, the addition law's coefficient.
const D2: Fe = Fe([
    0x69b9426b2f159,
    0x35050762add7a,
    0x3cf44c0038052,
    0x6738cc7407977,
    0x2406d9dc56dff,
]);

/// sqrt(-1) = 2^((p-1)/4). p is 5 mod 8, so the square-root exponent below
/// yields a root of ±u and this is the fixup for the wrong one.
const SQRT_M1: Fe = Fe([
    0x61b274a0ea0b0,
    0x0d5a5fc8f189d,
    0x7ef5e9cbd0c60,
    0x78595a6804c9e,
    0x2b8324804fc1d,
]);

/// p-2: the inversion exponent (Fermat's little theorem).
const P_MINUS_2: [u8; 32] = [
    0xeb, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
    0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x7f,
];

/// (p-5)/8: the square-root exponent for p = 5 (mod 8).
const P_MINUS_5_DIV_8: [u8; 32] = [
    0xfd, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
    0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x0f,
];

/// L = 2^252 + 27742317777372353535851937790883648493, the prime order of the
/// base point's subgroup, as 64-bit words least-significant first.
const L: [u64; 4] = [
    0x5812_631a_5cf5_d3ed,
    0x14de_f9de_a2f7_9cd6,
    0x0000_0000_0000_0000,
    0x1000_0000_0000_0000,
];

/// The base point B, in its own 32-byte compressed encoding rather than as
/// hand-entered coordinates: it is decompressed through the same path a public
/// key takes, so the encoder/decoder pair is exercised on a point whose
/// coordinates are known before it is ever asked about one that is not.
const BASE_POINT: [u8; 32] = [
    0x58, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66,
    0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66,
];

/// 51 bits: the limb width. Five of them hold a field element.
const MASK: u64 = (1 << 51) - 1;
const MASK128: u128 = (1 << 51) - 1;

/// 2p, limb by limb — what `sub` adds before subtracting so no limb borrows.
/// Each is twice the corresponding limb of p = 2^255 - 19.
const TWO_P: [u64; 5] = [
    0xfffffffffffda,
    0xffffffffffffe,
    0xffffffffffffe,
    0xffffffffffffe,
    0xffffffffffffe,
];

pub const PUBLIC_KEY_LEN: usize = 32;
pub const SIGNATURE_LEN: usize = 64;

// ---- GF(2^255 - 19) ----

/// A field element as five 51-bit limbs, least significant first.
///
/// Every operation carry-propagates before returning, so a limb is always at
/// most 2^51 and the representation is WEAKLY reduced (a value may still
/// exceed p; only `to_bytes` reduces canonically). Reducing eagerly costs a
/// few adds and buys the property that makes this auditable: no operation has
/// a precondition about how reduced its inputs are, so no sequence of them can
/// overflow.
#[derive(Clone, Copy)]
struct Fe([u64; 5]);

impl Fe {
    const ZERO: Fe = Fe([0, 0, 0, 0, 0]);
    const ONE: Fe = Fe([1, 0, 0, 0, 0]);

    fn add(&self, other: &Fe) -> Fe {
        let [a0, a1, a2, a3, a4] = self.0;
        let [b0, b1, b2, b3, b4] = other.0;
        carry_u64([a0 + b0, a1 + b1, a2 + b2, a3 + b3, a4 + b4])
    }

    fn sub(&self, other: &Fe) -> Fe {
        let [a0, a1, a2, a3, a4] = self.0;
        let [b0, b1, b2, b3, b4] = other.0;
        let [p0, p1, p2, p3, p4] = TWO_P;
        // Adding 2p first keeps every limb non-negative: a limb of `other` is
        // at most 2^51 (see the invariant above) and every limb of 2p exceeds
        // that, so no subtraction borrows.
        carry_u64([
            a0 + p0 - b0,
            a1 + p1 - b1,
            a2 + p2 - b2,
            a3 + p3 - b3,
            a4 + p4 - b4,
        ])
    }

    fn neg(&self) -> Fe {
        Fe::ZERO.sub(self)
    }

    fn mul(&self, other: &Fe) -> Fe {
        let [a0, a1, a2, a3, a4] = self.0.map(u128::from);
        let [b0, b1, b2, b3, b4] = other.0.map(u128::from);
        // A product that lands above limb 4 wraps to limb 0 scaled by 19,
        // since 2^255 = 19 (mod p).
        let (b1_19, b2_19, b3_19, b4_19) = (b1 * 19, b2 * 19, b3 * 19, b4 * 19);
        carry_u128([
            a0 * b0 + a1 * b4_19 + a2 * b3_19 + a3 * b2_19 + a4 * b1_19,
            a0 * b1 + a1 * b0 + a2 * b4_19 + a3 * b3_19 + a4 * b2_19,
            a0 * b2 + a1 * b1 + a2 * b0 + a3 * b4_19 + a4 * b3_19,
            a0 * b3 + a1 * b2 + a2 * b1 + a3 * b0 + a4 * b4_19,
            a0 * b4 + a1 * b3 + a2 * b2 + a3 * b1 + a4 * b0,
        ])
    }

    fn sq(&self) -> Fe {
        self.mul(self)
    }

    /// Square-and-multiply over a 255-bit exponent, most significant bit
    /// first. The hand-optimised addition chains the reference implementations
    /// use are three times faster and immeasurably harder to check; a boot
    /// shim verifies one signature, so this takes the readable one.
    fn pow(&self, exponent: &[u8; 32]) -> Fe {
        let mut result = Fe::ONE;
        for i in (0..256).rev() {
            result = result.sq();
            if bit(exponent, i) == 1 {
                result = result.mul(self);
            }
        }
        result
    }

    fn invert(&self) -> Fe {
        self.pow(&P_MINUS_2)
    }

    /// The canonical 32-byte little-endian encoding: fully reduced mod p.
    fn to_bytes(self) -> [u8; 32] {
        let [mut t0, mut t1, mut t2, mut t3, mut t4] = carry_u64(self.0).0;
        // Weak reduction leaves a value in [0, 2p); decide whether p must come
        // off by adding 19 and watching for the carry out of the top limb.
        let mut q = (t0 + 19) >> 51;
        q = (t1 + q) >> 51;
        q = (t2 + q) >> 51;
        q = (t3 + q) >> 51;
        q = (t4 + q) >> 51;
        t0 += 19 * q;
        t1 += t0 >> 51;
        t0 &= MASK;
        t2 += t1 >> 51;
        t1 &= MASK;
        t3 += t2 >> 51;
        t2 &= MASK;
        t4 += t3 >> 51;
        t3 &= MASK;
        t4 &= MASK;

        let words = [
            t0 | (t1 << 51),
            (t1 >> 13) | (t2 << 38),
            (t2 >> 26) | (t3 << 25),
            (t3 >> 39) | (t4 << 12),
        ];
        let mut out = [0u8; 32];
        let (chunks, _) = out.as_chunks_mut::<8>();
        for (dst, word) in chunks.iter_mut().zip(words.iter()) {
            *dst = word.to_le_bytes();
        }
        out
    }

    /// Little-endian decode. Bit 255 is IGNORED (it is the sign bit in a point
    /// encoding, never part of the field element), and a value at or above p
    /// is accepted here and caught by the canonicity check in `decompress`.
    fn from_bytes(bytes: &[u8; 32]) -> Fe {
        let (chunks, _) = bytes.as_chunks::<8>();
        let word = |i: usize| {
            chunks
                .get(i)
                .copied()
                .map_or(0, |w: [u8; 8]| u64::from_le_bytes(w))
        };
        let (w0, w1, w2, w3) = (word(0), word(1), word(2), word(3));
        Fe([
            w0 & MASK,
            ((w0 >> 51) | (w1 << 13)) & MASK,
            ((w1 >> 38) | (w2 << 26)) & MASK,
            ((w2 >> 25) | (w3 << 39)) & MASK,
            (w3 >> 12) & MASK,
        ])
    }

    fn is_zero(self) -> bool {
        self.to_bytes() == [0u8; 32]
    }

    /// RFC 8032's sign convention: the least significant bit of the canonical
    /// encoding.
    fn is_odd(self) -> bool {
        self.to_bytes().first().is_some_and(|b| b & 1 == 1)
    }
}

impl PartialEq for Fe {
    fn eq(&self, other: &Fe) -> bool {
        self.to_bytes() == other.to_bytes()
    }
}

/// Propagate carries so every limb is at most 2^51. The top limb's overflow
/// wraps into limb 0 scaled by 19 (2^255 = 19 mod p), which can itself carry,
/// hence the final pass.
fn carry_u64(limbs: [u64; 5]) -> Fe {
    let [mut t0, mut t1, mut t2, mut t3, mut t4] = limbs;
    t1 += t0 >> 51;
    t0 &= MASK;
    t2 += t1 >> 51;
    t1 &= MASK;
    t3 += t2 >> 51;
    t2 &= MASK;
    t4 += t3 >> 51;
    t3 &= MASK;
    t0 += 19 * (t4 >> 51);
    t4 &= MASK;
    t1 += t0 >> 51;
    t0 &= MASK;
    Fe([t0, t1, t2, t3, t4])
}

fn carry_u128(limbs: [u128; 5]) -> Fe {
    let [mut t0, mut t1, mut t2, mut t3, mut t4] = limbs;
    t1 += t0 >> 51;
    t0 &= MASK128;
    t2 += t1 >> 51;
    t1 &= MASK128;
    t3 += t2 >> 51;
    t2 &= MASK128;
    t4 += t3 >> 51;
    t3 &= MASK128;
    t0 += 19 * (t4 >> 51);
    t4 &= MASK128;
    t1 += t0 >> 51;
    t0 &= MASK128;
    Fe([t0 as u64, t1 as u64, t2 as u64, t3 as u64, t4 as u64])
}

/// Bit `i` of a little-endian byte string, or 0 past its end.
fn bit(bytes: &[u8], i: usize) -> u8 {
    bytes.get(i >> 3).map_or(0, |b| (b >> (i & 7)) & 1)
}

// ---- the group ----

/// A curve point in extended coordinates (X:Y:Z:T), where x = X/Z, y = Y/Z and
/// T = XY/Z.
#[derive(Clone, Copy)]
struct Point {
    x: Fe,
    y: Fe,
    z: Fe,
    t: Fe,
}

impl Point {
    const IDENTITY: Point = Point {
        x: Fe::ZERO,
        y: Fe::ONE,
        z: Fe::ONE,
        t: Fe::ZERO,
    };

    /// add-2008-hwcd-3. Complete for a = -1 with d a non-square, so it needs
    /// no special case — including P + P and P + (-P).
    fn add(&self, other: &Point) -> Point {
        let a = self.y.sub(&self.x).mul(&other.y.sub(&other.x));
        let b = self.y.add(&self.x).mul(&other.y.add(&other.x));
        let c = self.t.mul(&D2).mul(&other.t);
        let d = self.z.mul(&other.z);
        let d = d.add(&d);
        let e = b.sub(&a);
        let f = d.sub(&c);
        let g = d.add(&c);
        let h = b.add(&a);
        Point {
            x: e.mul(&f),
            y: g.mul(&h),
            z: f.mul(&g),
            t: e.mul(&h),
        }
    }

    /// dbl-2008-hwcd. Algebraically `add(self, self)`, which the tests check,
    /// but it skips the T multiplications the general law needs.
    fn double(&self) -> Point {
        let a = self.x.sq();
        let b = self.y.sq();
        let c = self.z.sq();
        let c = c.add(&c);
        let d = a.neg();
        let e = self.x.add(&self.y).sq().sub(&a).sub(&b);
        let g = d.add(&b);
        let f = g.sub(&c);
        let h = d.sub(&b);
        Point {
            x: e.mul(&f),
            y: g.mul(&h),
            z: f.mul(&g),
            t: e.mul(&h),
        }
    }

    fn neg(&self) -> Point {
        Point {
            x: self.x.neg(),
            y: self.y,
            z: self.z,
            t: self.t.neg(),
        }
    }

    /// [scalar]self, double-and-add, most significant bit first.
    ///
    /// Deliberately NOT constant time: it branches on the scalar's bits. Both
    /// scalars a verification multiplies by are public — one is the signature's
    /// own S, the other the hash of data that travels with it — so there is no
    /// secret for the timing to leak.
    fn scalar_mul(&self, scalar: &[u8; 32]) -> Point {
        let mut acc = Point::IDENTITY;
        for i in (0..256).rev() {
            acc = acc.double();
            if bit(scalar, i) == 1 {
                acc = acc.add(self);
            }
        }
        acc
    }

    /// The 32-byte encoding: y with x's sign in the top bit.
    fn compress(&self) -> [u8; 32] {
        let zinv = self.z.invert();
        let x = self.x.mul(&zinv);
        let y = self.y.mul(&zinv);
        let mut out = y.to_bytes();
        if let Some(top) = out.last_mut() {
            *top |= u8::from(x.is_odd()) << 7;
        }
        out
    }

    /// Recover a point from its encoding, or `None` if the bytes are not one.
    ///
    /// Rejects a non-canonical y (an encoding of y + p, which names the same
    /// point through different bytes), a y for which no x exists, and the one
    /// x = 0 case where the sign bit would carry information the point does
    /// not have.
    fn decompress(bytes: &[u8; 32]) -> Option<Point> {
        let sign = bytes.last().map_or(0, |b| b >> 7);
        let mut without_sign = *bytes;
        if let Some(top) = without_sign.last_mut() {
            *top &= 0x7f;
        }
        let y = Fe::from_bytes(&without_sign);
        if y.to_bytes() != without_sign {
            return None; // y >= p: a second encoding of the same point
        }
        // x^2 = (y^2 - 1) / (d y^2 + 1) = u/v.
        let yy = y.sq();
        let u = yy.sub(&Fe::ONE);
        let v = yy.mul(&D).add(&Fe::ONE);
        // The candidate root, as (u/v)^((p+3)/8) without an inversion:
        // u v^3 (u v^7)^((p-5)/8).
        let v3 = v.sq().mul(&v);
        let v7 = v3.sq().mul(&v);
        let mut x = u.mul(&v3).mul(&u.mul(&v7).pow(&P_MINUS_5_DIV_8));
        let check = v.mul(&x.sq());
        if check != u {
            if check == u.neg() {
                x = x.mul(&SQRT_M1);
            } else {
                return None; // u/v is not a square: no such point
            }
        }
        if x.is_zero() && sign == 1 {
            return None; // -0 is not an encoding
        }
        if x.is_odd() != (sign == 1) {
            x = x.neg();
        }
        Some(Point {
            x,
            y,
            z: Fe::ONE,
            t: x.mul(&y),
        })
    }

    /// Whether this point has order 1, 2, 4 or 8 — the torsion subgroup that
    /// is not the prime-order group signatures live in. Such a public key
    /// verifies signatures nobody needed a private key to make.
    fn is_small_order(&self) -> bool {
        let eightfold = self.double().double().double();
        eightfold.is_identity()
    }

    /// Whether this point lies in the prime-order subgroup, i.e. carries NO
    /// torsion component: `[L]P` is the identity exactly then.
    ///
    /// This is the whole class that `is_small_order` only sampled. A key
    /// `A = B + T` for a torsion point `T` is not small order and passes that
    /// check, yet it is the key every torsion-shaped forgery is built on, and
    /// it is also where cofactored verifiers (libsodium, ZIP-215) and
    /// cofactorless ones like this disagree about the same bytes. An HONEST
    /// key cannot fail this: a public key is `[a]B`, which is in the
    /// prime-order subgroup by construction.
    fn is_torsion_free(&self) -> bool {
        self.scalar_mul(&store_words(L)).is_identity()
    }

    fn is_identity(&self) -> bool {
        // Projectively: X = 0 and Y = Z, which needs no inversion.
        self.x.is_zero() && self.y == self.z
    }
}

// ---- scalars mod L ----

fn load_words(bytes: &[u8; 32]) -> [u64; 4] {
    let (chunks, _) = bytes.as_chunks::<8>();
    let word = |i: usize| {
        chunks
            .get(i)
            .copied()
            .map_or(0, |w: [u8; 8]| u64::from_le_bytes(w))
    };
    [word(0), word(1), word(2), word(3)]
}

fn store_words(words: [u64; 4]) -> [u8; 32] {
    let mut out = [0u8; 32];
    let (chunks, _) = out.as_chunks_mut::<8>();
    for (dst, word) in chunks.iter_mut().zip(words.iter()) {
        *dst = word.to_le_bytes();
    }
    out
}

/// Whether `value >= L`, comparing from the most significant word down.
fn at_least_l(value: [u64; 4]) -> bool {
    for (v, l) in value.iter().rev().zip(L.iter().rev()) {
        if v != l {
            return v > l;
        }
    }
    true // equal to L
}

fn sub_l(value: [u64; 4]) -> [u64; 4] {
    let mut out = [0u64; 4];
    let mut borrow = 0u64;
    for ((slot, v), l) in out.iter_mut().zip(value.iter()).zip(L.iter()) {
        let (d, b1) = v.overflowing_sub(*l);
        let (d, b2) = d.overflowing_sub(borrow);
        *slot = d;
        borrow = u64::from(b1 || b2);
    }
    out
}

/// A signature's S must be the canonical representative mod L. Without this,
/// `S + L` — trivially computable by anyone holding the signature — is a
/// second signature that verifies for the same message.
fn is_canonical_scalar(bytes: &[u8; 32]) -> bool {
    !at_least_l(load_words(bytes))
}

/// A 64-byte little-endian hash reduced mod L.
///
/// Bit by bit, most significant first: `r = 2r + bit`, then one conditional
/// subtraction, which suffices because doubling a value below L leaves it
/// below 2L. The reference implementations use a Barrett-style reduction over
/// packed 21-bit limbs that is far faster and essentially unreviewable; this
/// runs 512 times per verification and takes microseconds.
fn reduce_wide(hash: &[u8; 64]) -> [u8; 32] {
    let mut r = [0u64; 4];
    for byte in hash.iter().rev() {
        for shift in (0..8).rev() {
            // r = 2r + bit: r < L < 2^253, so this cannot overflow 4 words.
            let mut carry = u64::from((byte >> shift) & 1);
            for slot in r.iter_mut() {
                let next = *slot >> 63;
                *slot = (*slot << 1) | carry;
                carry = next;
            }
            if at_least_l(r) {
                r = sub_l(r);
            }
        }
    }
    store_words(r)
}

// ---- verification ----

/// Whether `signature` is a valid ed25519 signature of `message` under
/// `public_key`.
///
/// Every failure is this one `false`: a malformed key, a malformed signature,
/// a non-canonical S, a small-order key and a signature that simply does not
/// verify are not distinguished. That is deliberate — the caller has exactly
/// one question and no way to spell an answer that is not "reject".
#[must_use]
pub fn verify(
    public_key: &[u8; PUBLIC_KEY_LEN],
    message: &[u8],
    signature: &[u8; SIGNATURE_LEN],
) -> bool {
    let (chunks, _) = signature.as_chunks::<32>();
    let (Some(r_bytes), Some(s_bytes)) = (chunks.first(), chunks.get(1)) else {
        return false;
    };
    if !is_canonical_scalar(s_bytes) {
        return false;
    }
    let Some(a) = Point::decompress(public_key) else {
        return false;
    };
    // The key must be in the prime-order subgroup and must not be the
    // identity — between them, every point with a torsion component and every
    // small-order point. `is_torsion_free` alone would admit the identity
    // (`[L]O` is `O`), and the identity signs for everybody.
    if a.is_identity() || !a.is_torsion_free() {
        return false;
    }
    // R is decompressed ONLY to refuse a small-order one. With A already
    // torsion-free this is defence in depth rather than the load-bearing
    // check — see `a_mixed_order_key_is_refused`, which is refused by the key
    // policy above — but R is attacker-supplied where A is pinned, and three
    // doublings are not worth reasoning about. The equation below still
    // compares ENCODINGS, so a non-canonical R stays a rejection either way:
    // it fails to decompress here, and could never equal a canonical
    // re-encoding there.
    let Some(r_point) = Point::decompress(r_bytes) else {
        return false;
    };
    if r_point.is_small_order() {
        return false;
    }
    let Some(base) = Point::decompress(&BASE_POINT) else {
        return false;
    };

    let mut hasher = sha512::Sha512::new();
    hasher.update(r_bytes);
    hasher.update(public_key);
    hasher.update(message);
    let k = reduce_wide(&hasher.finalize());

    // R = [S]B - [k]A. Comparing ENCODINGS rather than decompressing R is what
    // makes a non-canonical R a rejection for free.
    let expected = base.scalar_mul(s_bytes).add(&a.scalar_mul(&k).neg());
    expected.compress() == *r_bytes
}

