//! Ed25519 signature VERIFICATION (RFC 8032), pure `std` — the authenticity
//! half of a td deployment, and the one thing hashes cannot give it.
//!
//! Verify only, and that is the point rather than a limitation. Nothing here
//! generates a key, derives a public key, or produces a signature, so no
//! secret ever reaches this code and there is no constant-time obligation to
//! meet: every input is public (a pinned public key, a signature and a
//! manifest that ship together in the clear), and the code branches on them
//! freely. SIGNING stays host-side in `td-net`, where `ring` already does it
//! for narinfos, and a signing key never enters the target at all.
//!
//! Dependency-free for the reason the rest of the engine is: its INTENDED
//! consumer is `td-boot`, which runs in the boot shim before any store exists,
//! and no shipped td crate outside the network tools carries an external
//! crate. Nothing includes it yet — the `#[path]` include lands with the
//! verifying boot shim — and when it does it must declare BOTH this module and
//! `sha512` at its crate root, since `crate::sha512` is how this one reaches
//! the hash and that spelling resolves identically inside the engine lib and
//! inside an including binary. `net`'s test build already does exactly that.
//!
//! Correctness is pinned three ways, because a verifier that is merely
//! SLIGHTLY wrong still accepts every genuine signature and so is discovered
//! by nobody. Every constant below is RE-DERIVED in the tests from the
//! definition its name states — d from -121665/121666, 2d from d, sqrt(-1) by
//! squaring it, 2p by reducing it to zero — so a mistyped limb reds rather
//! than sitting there being almost right. The group law is checked against its
//! own algebra (the base point's order is L, `add(P,P) == double(P)`,
//! associativity). And `net/src/ed25519_cross.rs` signs with `ring` and
//! verifies HERE on fresh keys every run, holding the two implementations
//! against each other rather than against one recorded vector; the signatures
//! that check-in produced are the fixtures at the bottom of this file, so this
//! crate stays testable with no dependency present.
//!
//! Verification is STRICT — at least as strict as `ed25519-dalek`'s
//! `verify_strict`, and deliberately stronger about torsion. Every one of
//! these is a rejection:
//!
//!   - `S >= L` (the malleability case: `S + L` verifies under a verifier that
//!     omits this and is a SECOND valid signature for one message);
//!   - a non-canonical public key encoding (`y >= p`);
//!   - a public key OUTSIDE the prime-order subgroup, or the identity.
//!     That is the whole torsion class rather than a sample of it, and it is
//!     strictly stronger than `verify_strict`, which refuses a small-order key
//!     but admits a MIXED-order one. It has to be: `A = B + T` for a torsion
//!     point `T` is not small order, and any message whose hash comes out even
//!     then has a forgery with `R` at the identity — `a_mixed_order_key_is_refused`
//!     builds one and asserts it satisfies the verification equation before
//!     asserting it is refused, so the check cannot pass for the wrong reason.
//!     No honest key can fail this, since a public key is `[a]B`;
//!   - a small-order `R` — defence in depth once the key is torsion-free, but
//!     `R` is attacker-supplied where the key is pinned;
//!   - a non-canonical `R`, twice over: it fails to decompress, and could
//!     never equal the canonical re-encoding the equation compares against.
//!
//! The equation is still checked by comparing ENCODINGS — the expected point
//! is re-encoded and its 32 bytes compared to `R` — rather than by
//! decompressing `R` and comparing points. `R` is decompressed only to ask
//! whether it is small order.
//!
//! td signs and verifies with the same tools, so nothing legitimate is near
//! those edges; a strict verifier costs nothing and refuses the whole class.

use crate::sha512;

