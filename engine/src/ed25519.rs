    #[test]
    fn a_small_order_key_cannot_sign_for_everything() {
        // The danger a small-order key IS, built rather than described. Take A
        // = the identity: [k]A is the identity whatever k is, so the
        // verification equation collapses to R = [S]B, which does not mention
        // the message at all. Any S below L therefore yields a signature that
        // verifies for EVERY message under that key — no private key needed.
        //
        // An all-zero signature would be rejected by the equation itself and
        // so proves nothing about the refusal; this one is refused only
        // because the key is.
        let key = Point::IDENTITY.compress();
        let mut s = [0u8; 32];
        if let Some(slot) = s.first_mut() {
            *slot = 7;
        }
        let r = base().scalar_mul(&s).compress();
        let mut signature = [0u8; 64];
        if let Some(dst) = signature.get_mut(..32) {
            dst.copy_from_slice(&r);
        }
        if let Some(dst) = signature.get_mut(32..) {
            dst.copy_from_slice(&s);
        }
        for message in [b"one message".as_slice(), b"a completely different one"] {
            assert!(
                !verify(&key, message, &signature),
                "a small-order key signed for an arbitrary message"
            );
        }
    }

    /// The order-2 point, y = -1.
    fn torsion_point() -> Option<Point> {
        let order_two: [u8; 32] =
            from_hex("ecffffffffffffffffffffffffffffffffffffffffffffffffffffffffffff7f");
        Point::decompress(&order_two)
    }

    #[test]
    fn the_prime_order_subgroup_check_separates_honest_keys_from_torsion() {
        // What `is_small_order` alone could not say. Each of these is a point
        // the check must classify differently, and the Option comparison makes
        // a decompression failure a red rather than a skip.
        assert!(base().is_torsion_free(), "an honest key is [a]B");
        assert_eq!(
            torsion_point().map(|t| t.is_torsion_free()),
            Some(false),
            "a pure torsion point is not in the prime-order subgroup"
        );
        assert_eq!(
            torsion_point().map(|t| base().add(&t).is_torsion_free()),
            Some(false),
            "B + T carries a torsion component"
        );
        assert_eq!(
            torsion_point().map(|t| base().add(&t).is_small_order()),
            Some(false),
            "B + T is MIXED order — which is exactly why is_small_order misses it"
        );
        // The identity satisfies [L]O = O, so this check alone would admit it;
        // `verify` refuses it separately.
        assert!(Point::IDENTITY.is_torsion_free());
        assert!(Point::IDENTITY.is_identity());
    }

    /// `challenge` for a candidate signature: k = H(R, A, M) reduced mod L.
    fn challenge(r_bytes: &[u8; 32], key: &[u8; 32], message: &[u8]) -> [u8; 32] {
        let mut hasher = crate::sha512::Sha512::new();
        hasher.update(r_bytes);
        hasher.update(key);
        hasher.update(message);
        reduce_wide(&hasher.finalize())
    }

    fn signature_of(r_bytes: &[u8; 32], s: &[u8; 32]) -> [u8; 64] {
        let mut signature = [0u8; 64];
        if let Some(dst) = signature.get_mut(..32) {
            dst.copy_from_slice(r_bytes);
        }
        if let Some(dst) = signature.get_mut(32..) {
            dst.copy_from_slice(s);
        }
        signature
    }

    /// `scalar + small` mod L. `scalar` is below L and `small` is tiny, so the
    /// sum is below 2L and one conditional subtraction reduces it.
    fn scalar_plus(scalar: &[u8; 32], small: u64) -> [u8; 32] {
        let mut words = load_words(scalar);
        let mut carry = u128::from(small);
        for slot in words.iter_mut() {
            let sum = u128::from(*slot) + carry;
            *slot = sum as u64;
            carry = sum >> 64;
        }
        if at_least_l(words) {
            words = sub_l(words);
        }
        store_words(words)
    }

    #[test]
    fn a_mixed_order_key_is_refused() {
        // The signature a small-order KEY refusal does not catch, built rather
        // than described. Take A = B + T with T of order 2 and the "private
        // key" a = 1: A is not small order, so that check passes it. Sign
        // ordinarily with a nonce r = 5, giving S = 5 + k:
        //
        //     [S]B - [k]A = [5+k]B - [k]B - [k]T = [5]B - [k]T
        //
        // which is [5]B — and so equals R — whenever k is EVEN, since T doubles
        // to nothing. R = [5]B is NOT small order, so the small-order-R check
        // below cannot be what refuses this: only the prime-order-subgroup
        // requirement on A can, which is what this test pins.
        let Some(t) = torsion_point() else {
            return;
        };
        let a = base().add(&t);
        assert!(!a.is_small_order(), "A must survive the small-order check");
        let key = a.compress();
        let nonce = scalar_plus(&[0u8; 32], 5);
        let r_point = base().scalar_mul(&nonce);
        assert!(!r_point.is_small_order(), "R must not be small order");
        let r_bytes = r_point.compress();

        let mut built = false;
        for probe in 0u8..64 {
            let message = [probe];
            let k = challenge(&r_bytes, &key, &message);
            if bit(&k, 0) == 1 {
                continue; // odd k leaves [k]T = T, so the equation misses R
            }
            let signature = signature_of(&r_bytes, &scalar_plus(&k, 5));
            // The equation really is satisfied — this is refused for the key it
            // is under, not because it fails to verify.
            let expected = base()
                .scalar_mul(&scalar_plus(&k, 5))
                .add(&a.scalar_mul(&k).neg());
            assert_eq!(
                expected.compress(),
                r_bytes,
                "probe {probe}: the constructed signature does not satisfy the equation"
            );
            assert!(
                !verify(&key, &message, &signature),
                "probe {probe}: a signature under a mixed-order key was accepted"
            );
            built = true;
            break;
        }
        assert!(built, "no message in 64 probes produced an even k");
    }

    #[test]
    fn a_small_order_r_is_refused() {
        // The other half, isolated so it pins the R check and nothing else.
        // The key here is the base point itself — torsion-free, the shape an
        // honest key has — so the subgroup requirement above passes it. With
        // a = 1, choosing R = the identity and S = k gives
        //
        //     [S]B - [k]A = [k]B - [k]B = O = R
        //
        // for EVERY message, with no parity condition. It is a real signature
        // by whoever holds a, and a degenerate one: r = 0, so R carries no
        // nonce at all. Only the small-order-R refusal rejects it.
        let key = base().compress();
        let r_bytes = Point::IDENTITY.compress();
        for message in [b"one message".as_slice(), b"a completely different one"] {
            let k = challenge(&r_bytes, &key, message);
            let signature = signature_of(&r_bytes, &k);
            let expected = base().scalar_mul(&k).add(&base().scalar_mul(&k).neg());
            assert_eq!(
                expected.compress(),
                r_bytes,
                "the constructed signature does not satisfy the equation"
            );
            assert!(
                !verify(&key, message, &signature),
                "a signature with R at the identity was accepted"
            );
        }
    }

    #[test]
    fn s_at_or_above_l_is_refused() {
        // Malleability: (S + L) mod L is S, so a verifier that reduces rather
        // than REFUSING would accept a second signature for the same message
        // that nobody with the private key ever produced.
        let Some((_, len, public_hex, signature_hex)) = RING_VECTORS.first().copied() else {
            return;
        };
        let public: [u8; 32] = from_hex(public_hex);
        let signature: [u8; 64] = from_hex(signature_hex);
        assert!(verify(&public, &vector_message(len), &signature));

        let s: [u8; 32] = signature
            .get(32..64)
            .and_then(|s| s.try_into().ok())
            .unwrap_or([0u8; 32]);
        let mut words = load_words(&s);
        let mut carry = 0u128;
        for (slot, l) in words.iter_mut().zip(L.iter()) {
            let sum = u128::from(*slot) + u128::from(*l) + carry;
            *slot = sum as u64;
            carry = sum >> 64;
        }
        let mut malleable = signature;
        if let Some(dst) = malleable.get_mut(32..64) {
            dst.copy_from_slice(&store_words(words));
        }
        assert_ne!(malleable, signature);
        assert!(!verify(&public, &vector_message(len), &malleable));
    }

