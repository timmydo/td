    /// Decode a hex literal, REFUSING anything that is not exactly `N` bytes
    /// of lowercase hex. The forgiving version this replaces mapped a stray
    /// character to nibble 0 and right-padded a short string, so a mistyped
    /// literal in a negative test still decoded to *some* value and the
    /// assertion could hold for a reason that had nothing to do with the
    /// property being tested.
    fn hex_nibble(c: u8) -> Option<u8> {
        match c {
            b'0'..=b'9' => Some(c - b'0'),
            b'a'..=b'f' => Some(c - b'a' + 10),
            _ => None,
        }
    }

    fn from_hex<const N: usize>(s: &str) -> [u8; N] {
        assert_eq!(s.len(), N * 2, "hex literal must be {N} bytes: {s}");
        let (pairs, _) = s.as_bytes().as_chunks::<2>();
        let decoded: Option<Vec<u8>> = pairs
            .iter()
            .map(|pair| {
                let [hi, lo] = *pair;
                Some((hex_nibble(hi)? << 4) | hex_nibble(lo)?)
            })
            .collect();
        let decoded = decoded.unwrap_or_default();
        assert_eq!(decoded.len(), N, "not lowercase hex: {s}");
        let mut out = [0u8; N];
        out.copy_from_slice(&decoded);
        out
    }

